module.exports = (sequelize, DataTypes) =>
  sequelize.define(
    'Notification',
    {
      notificationId: { type: DataTypes.BIGINT, autoIncrement: true, primaryKey: true, field: 'notification_id' },
      notificationUuid: { type: DataTypes.UUID, allowNull: false, unique: true, defaultValue: DataTypes.UUIDV4, field: 'notification_uuid' },
      tenantUuid: { type: DataTypes.UUID, allowNull: false, field: 'tenant_uuid' },
      channel: { type: DataTypes.STRING(20), allowNull: false, defaultValue: 'EMAIL', field: 'channel' },
      templateKey: { type: DataTypes.STRING(60), allowNull: false, field: 'template_key' },
      category: { type: DataTypes.STRING(20), allowNull: false, field: 'category' },
      recipientAddress: { type: DataTypes.STRING(255), allowNull: false, field: 'recipient_address' },
      recipientName: { type: DataTypes.STRING(150), allowNull: true, field: 'recipient_name' },
      subject: { type: DataTypes.STRING(255), allowNull: false, field: 'subject' },
      bodyText: { type: DataTypes.TEXT, allowNull: true, field: 'body_text' },
      bodyHtml: { type: DataTypes.TEXT, allowNull: true, field: 'body_html' },
      status: { type: DataTypes.STRING(20), allowNull: false, defaultValue: 'PENDING', field: 'status' },
      priority: { type: DataTypes.SMALLINT, allowNull: false, defaultValue: 5, field: 'priority' },
      scheduledAt: { type: DataTypes.DATE, allowNull: false, field: 'scheduled_at' },
      nextAttemptAt: { type: DataTypes.DATE, allowNull: false, field: 'next_attempt_at' },
      lockedUntil: { type: DataTypes.DATE, allowNull: true, field: 'locked_until' },
      attempts: { type: DataTypes.SMALLINT, allowNull: false, defaultValue: 0, field: 'attempts' },
      maxAttempts: { type: DataTypes.SMALLINT, allowNull: false, defaultValue: 5, field: 'max_attempts' },
      lastError: { type: DataTypes.STRING(500), allowNull: true, field: 'last_error' },
      provider: { type: DataTypes.STRING(30), allowNull: true, field: 'provider' },
      providerMessageId: { type: DataTypes.STRING(255), allowNull: true, field: 'provider_message_id' },
      sentAt: { type: DataTypes.DATE, allowNull: true, field: 'sent_at' },
      idempotencyKey: { type: DataTypes.STRING(100), allowNull: true, field: 'idempotency_key' },
      sourceService: { type: DataTypes.STRING(50), allowNull: true, field: 'source_service' },
      sourceRef: { type: DataTypes.STRING(100), allowNull: true, field: 'source_ref' },
      createdBy: { type: DataTypes.BIGINT, allowNull: true, field: 'created_by' },
      createdOn: { type: DataTypes.DATE, allowNull: false, defaultValue: DataTypes.NOW, field: 'created_on' },
      modifiedOn: { type: DataTypes.DATE, allowNull: false, defaultValue: DataTypes.NOW, field: 'modified_on' },
    },
    {
      tableName: 'notifications',
      freezeTableName: true,
      timestamps: false,
      indexes: [
        { unique: true, fields: ['tenant_uuid', 'idempotency_key'] },
        { fields: ['status', 'next_attempt_at', 'priority'] },
        { fields: ['tenant_uuid', 'created_on'] },
        { fields: ['tenant_uuid', 'source_service', 'source_ref'] },
      ],
    },
  );
